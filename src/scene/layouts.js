// 星群:固定的伪随机分布,种子写死以保证每次加载完全一致(确定性渲染)。
// 它们不参与 morph,只随 starDensity 改变亮度,并做极轻微的滚动视差。
export const STARS = (() => {
  let seed = 20260824;
  const rand = () => {
    seed = (seed * 1664525 + 1013904223) % 4294967296;
    return seed / 4294967296;
  };
  return Array.from({ length: 34 }, () => ({
    x: rand(),
    y: rand() * 0.92 + 0.04,
    r: 0.0016 + rand() * 0.0026,
    // 视差深度:越小越"远",滚动时位移越少
    depth: 0.25 + rand() * 0.75,
    phase: rand(),
  }));
})();

